#!/bin/bash
# Writes fixtures/vaxia-starter.sql: a fresh install of config/sync with
# scripts/starter-content.php run, ready for a new site to import (see the
# README). Run after changing the config or the starter content, then commit
# the file. Uses the test stack (docker compose up -d web db) and a scratch
# database; the test databases are untouched.
#
# Nothing site-specific is kept: the admin account (uid 1) gets a random
# password nobody knows (sign in with `drush user:login`), Drupal's private
# key and cron key are removed (a site makes its own on first use), and
# caches, sessions, logs and flood records are emptied. Mail is sent again
# (the test baseline collects it instead), and the dump has no MariaDB-only
# sandbox line, so stock MySQL clients can import it.
set -euo pipefail
cd "$(dirname "$0")"
out=../../fixtures/vaxia-starter.sql
db() { docker compose exec -T db mariadb -uroot -proot "$@"; }
y() { docker compose exec -T -e VAXIA_SITE=config web bash -c "cd /var/www/vaxia && $1"; }

# A fresh install of the release config, in vaxia_config (the config copy).
test -s ../.build/d11-config-baseline.sql || { echo "Run ./install.sh first." >&2; exit 1; }
db -e "DROP DATABASE IF EXISTS vaxia_config; CREATE DATABASE vaxia_config; GRANT ALL ON vaxia_config.* TO 'vaxia'@'%'"
db vaxia_config < ../.build/d11-config-baseline.sql
y 'vendor/bin/drush cr -q'
y 'vendor/bin/drush php:script scripts/starter-content.php' | grep -E '^[a-z_]+: [0-9]+$|ready' || true

# Nothing site-specific.
y 'vendor/bin/drush php:eval "\$a = \Drupal\user\Entity\User::load(1); \$a->setPassword(bin2hex(random_bytes(24)))->setEmail(\"admin@example.com\")->set(\"init\", \"admin@example.com\")->save(); \Drupal::state()->deleteMultiple([\"system.private_key\", \"system.cron_key\", \"system.cron_last\", \"vaxia_core.starter_content\", \"system.test_mail_collector\"]); \Drupal::configFactory()->getEditable(\"system.mail\")->set(\"interface.default\", \"php_mail\")->save(); \Drupal::configFactory()->getEditable(\"system.site\")->set(\"mail\", \"admin@example.com\")->save(); \Drupal::configFactory()->getEditable(\"update.settings\")->set(\"notification.emails\", [])->save();"'
for t in $(db -N vaxia_config -e "SHOW TABLES LIKE 'cache%'") sessions watchdog flood semaphore key_value_expire; do
  db vaxia_config -e "TRUNCATE TABLE \`$t\`" 2>/dev/null || true
done

mkdir -p "$(dirname "$out")"
{
  echo "-- VAXIA starter site: a fresh install with the starter content (scripts/starter-content.php)."
  echo "-- Import into an empty database, point settings.php at it, then: drush cr; drush user:login"
  echo "-- Generated by tests/docker-d11/make-fixtures.sh: don't edit by hand."
  docker compose exec -T db mariadb-dump -uroot -proot --single-transaction --skip-dump-date --skip-comments vaxia_config | sed '/enable the sandbox mode/d'
} > "$out"
echo "Wrote $out ($(du -h "$out" | cut -f1))."
# The config copy holds the starter site now: put it back for config work.
VAXIA_SITE=config ./restore-baseline.sh >/dev/null
